#!/usr/bin/env bash
# Build UDLF-CSR (https://github.com/andreTomi/UDLF-CSR), pinned to a commit.
#
# Usage:
#   scripts/build_csr.sh [--full] [DEST_DIR] [COMMIT]
#
# Defaults: DEST_DIR=.udlf, COMMIT=b391800 (the repository has no tags yet).
# The binary ends up at DEST_DIR/UDLF-CSR/Source/bin/udlf.
#
# Without --full, only the engines that need no external library are built
# (dense and sparse: CPRR, CPRR_SPARSE, LHRR, LHRR_SPARSE). --full runs the
# UDLF-CSR Makefile, which also builds the MKL, BLAS (GraphBLAS) and Eigen
# engines and needs Intel MKL, SuiteSparse/GraphBLAS, Eigen, TBB and jemalloc.
# Both need g++ with C++23, OpenMP and TBB.
set -euo pipefail

FULL=0
if [ "${1:-}" = "--full" ]; then
    FULL=1
    shift
fi
DEST_DIR="${1:-.udlf}"
COMMIT="${2:-b391800}"
REPO_URL="https://github.com/andreTomi/UDLF-CSR.git"

mkdir -p "$DEST_DIR"
cd "$DEST_DIR"

if [ ! -d UDLF-CSR/.git ]; then
    git clone --quiet "$REPO_URL" UDLF-CSR
fi
git -C UDLF-CSR fetch --quiet origin
git -C UDLF-CSR -c advice.detachedHead=false checkout --quiet --force "$COMMIT"
cd UDLF-CSR/Source

if [ "$FULL" = 1 ]; then
    make udlf >/dev/null
    echo "UDLF-CSR $COMMIT (all engines) built at $(pwd)/bin/udlf"
    exit 0
fi

# Reduced build: register only the engines without external dependencies.
# The registry is generated in a separate file, the sources are not modified.
mkdir -p bin build_reduced
cat > build_reduced/Methods.cpp <<'EOF'
// Generated by pyUDLF scripts/build_csr.sh: engines without external libraries
#include "Cprr.hpp"
#include "CprrSparse.hpp"
#include "LHRR.hpp"
#include "LHRRSparse.hpp"
MethodRegister<Cprr> Cprr::signInMethod("CPRR");
MethodRegister<CprrSparse> CprrSparse::signInMethod("CPRR_SPARSE");
MethodRegister<LHRR> LHRR::signInMethod("LHRR");
MethodRegister<LHRRSparse> LHRRSparse::signInMethod("LHRR_SPARSE");
EOF
g++ -std=gnu++23 -O3 -march=native -fopenmp -ffast-math -D_GNU_SOURCE \
    -I./src -I./src/Config/hpp -I./src/Core/hpp -I./src/Methods/hpp \
    -I./src/Evaluation/hpp -I./src/Utils/hpp \
    src/Core/cpp/Main.cpp build_reduced/Methods.cpp \
    -o bin/udlf -lpthread -ltbb
echo "UDLF-CSR $COMMIT (dense and sparse engines) built at $(pwd)/bin/udlf"
